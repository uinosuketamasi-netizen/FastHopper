package com.example.fasthopper;

/*
 * ===============================================
 * 🔥 FastHopperMode
 * ===============================================
 *
 * 🎯 このenumがやること
 * ・Fast Hopper動作モード管理🔥
 *
 * ❌ やらないこと
 * ・GUI描画
 * ・Mixin処理
 * ・NBT保存
 *
 * 💡 一言
 * 👉「Fast Hopper動作タイプ定義🔥」
 * ===============================================
 */
public enum FastHopperMode
{
    /*
     * 🎯 安全重視
     * ・0.1～128倍設定のうち、安全寄りに制御
     * ・TPS保護向け
     * ・通常運用向け
     * ・バニラ互換重視
     *
     * 💡 一言
     * 👉「安全優先モード」
     */
    SAFE,

    /*
     * 🎯 高速重視
     * ・0.1～128倍設定のうち、高速寄りに制御
     * ・8倍まではCooldown短縮で高速化
     * ・8倍以降は1tick限界に到達
     * ・EXTRAとは違い、複数個搬送はしない
     *
     * 💡 一言
     * 👉「1tick限界モード」
     */
    EXTREME,

    /*
     * 🎯 複数搬送重視
     * ・0.1～128倍設定すべてに対応
     * ・8倍まではCooldown短縮
     * ・16倍以上は搬送量増加を狙う
     * ・16x=2個 / 32x=4個 / 64x=8個 / 128x=16個
     *
     * 💡 一言
     * 👉「真の超高速モード」
     */
    EXTRA
}